// Generates worker/lib/limits.js: the empirical ceilings of the anti-cheat plausibility model.
//   node tools/gen-limits.mjs [--runs 8] [--no-build] [--port 5191]      (GPU=1 for the metal backend)
// Method: play many full rounds with two autoplayers (the game's greedy bot and a stronger cluster-aware greedy), with
// and without opponents (without bots there is nothing to compete for the food, so it is the upper bound), in every mode
// and every daily twist; take the maximum score gain per 10 s for each radius band, the maximum eaten count per 10 s, the
// maximum final score per mode, the biggest duel gain, and the value range of every object kind in the city.
// worker/lib/validate.js multiplies these maxima by SOFT x2 (hidden) / HARD x3 (rejected). Re-run after changing
// balance (growth, values, map/buildings) and commit the result. Raw runs go to tools/out/sim-runs-train.json.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { openSim, simRound, root } from './sim-lib.mjs';
import { MODES, radiusAt, TRACE_STEP } from '../src/rules.js';
import { TWISTS, dailyInfo } from '../src/daily.js';

const arg = (k, d) => { const i = process.argv.indexOf(k); return i >= 0 ? process.argv[i + 1] : d; };
const RUNS = +arg('--runs', 8);
const BANDS = [2.2, 3.5, 5.5, 8, 12, 18, 28, 42, 62, 90, 130]; // = CFG.levels
const bandOf = (r) => { let i = 0; while (i < BANDS.length - 1 && r >= BANDS[i + 1]) i++; return i; };

// a calendar day for each daily twist
const dayFor = {};
for (let d = new Date('2026-11-01T00:00:00Z'), n = 0; n < 200 && Object.keys(dayFor).length < TWISTS.length; d.setUTCDate(d.getUTCDate() + 1), n++) {
  const day = d.toISOString().slice(0, 10), id = dailyInfo(day).twist.id;
  if (!dayFor[id]) dayFor[id] = day;
}

const sim = await openSim({ port: +arg('--port', 5191), noBuild: process.argv.includes('--no-build') });
const runs = [];
let values = null;
const plan = [];
for (const mode of ['classic', 'quick']) plan.push({ mode, day: null });
for (const tw of TWISTS) plan.push({ mode: 'daily', day: dayFor[tw.id] });
for (const bots of ['', 'bots=0']) {
  await sim.open(bots);
  for (const { mode, day } of plan) {
    for (const strategy of ['greedy', 'cluster']) {
      const n = mode === 'daily' ? Math.max(1, Math.round(RUNS / 4)) : RUNS;
      for (let i = 0; i < n; i++) {
        const r = await simRound(sim.page, { mode, day, strategy, collectValues: !values });
        if (r.values) { values = r.values; delete r.values; }
        r.variant = `${strategy}${bots ? '+nobots' : ''}`;
        runs.push(r);
        if (runs.length % 8 === 0) writeFileSync(path.join(root, 'tools/out/sim-runs-train.partial.json'), JSON.stringify(runs));
        process.stdout.write(`${mode}${day ? '/' + r.twist : ''} ${r.variant} score ${r.final.score} r ${r.final.radius}\n`);
      }
    }
  }
}
await sim.close();
writeFileSync(path.join(root, 'tools/out/sim-runs-train.json'), JSON.stringify(runs));

const modes = {};
let killMax = 0;
for (const mode of ['classic', 'quick', 'daily']) {
  const rs = runs.filter((r) => r.mode === mode);
  const gain = new Array(BANDS.length).fill(0), seen = new Array(BANDS.length).fill(0);
  let eaten10 = 0, cap = 0, maxKills = 0;
  for (const r of rs) {
    const tr = r.trace;
    let pS = 0, pE = 0, pK = 0, pT = 0;
    for (let i = 0; i < tr.t.length; i++) {
      const stretch = Math.max(1, (tr.t[i] - pT) / TRACE_STEP);
      const b = bandOf(radiusAt(pS, MODES[mode].growthK));
      if (tr.k[i] === pK) { gain[b] = Math.max(gain[b], (tr.s[i] - pS) / stretch); seen[b]++; }
      eaten10 = Math.max(eaten10, (tr.e[i] - pE) / stretch);
      pS = tr.s[i]; pE = tr.e[i]; pK = tr.k[i]; pT = tr.t[i];
    }
    cap = Math.max(cap, r.final.score); maxKills = Math.max(maxKills, r.final.kills);
    killMax = Math.max(killMax, ...r.killGains, ...(r.botScores.length ? [Math.max(...r.botScores) * 0.5] : [0]));
  }
  for (let b = 0; b < BANDS.length; b++) {   // unobserved bands: carry the lower band forward (x1.5); table is non-decreasing
    if (!seen[b]) gain[b] = (b ? gain[b - 1] : 50) * 1.5;
    if (b) gain[b] = Math.max(gain[b], gain[b - 1]);
  }
  modes[mode] = { gain: gain.map((v) => Math.ceil(v)), eaten10: Math.ceil(eaten10), cap: Math.ceil(cap), maxKills: Math.max(40, maxKills) };
  console.log(mode, JSON.stringify(modes[mode]), 'runs', rs.length);
}
for (const m of Object.values(modes)) m.killMax = Math.ceil(killMax);
const value = {};
for (const [k, [lo, hi]] of Object.entries(values)) value[k] = [Math.floor(lo), Math.ceil(hi * (k === 'building' || k === 'landmark' ? 1.3 : 1))];
const valueOther = Math.ceil(Math.max(...Object.values(value).map((v) => v[1])));

const out = `// GENERATED by tools/gen-limits.mjs -- do not edit by hand. Empirical maxima of autoplayer rounds
// (${runs.length} rounds: greedy + cluster-greedy, with / without bots, all modes + daily twists; ${new Date().toISOString().slice(0, 10)}).
// worker/lib/validate.js applies SOFT x2 (suspect) and HARD x3 (reject) factors on top of these.
// gain[band]  max score gained per ${TRACE_STEP} s by start-radius band (bands = CFG.levels)   eaten10  max objects eaten per ${TRACE_STEP} s
// cap         max final score   killMax  biggest single duel gain   value[kind] = [min, max] object value in the city (+30% for buildings)
export const LIMITS = ${JSON.stringify({ generated: new Date().toISOString().slice(0, 10), runs: runs.length, bands: BANDS, modes, value, valueOther }, null, 2).replace(/\[\s*([-\d.,\s]+?)\s*\]/g, (m, body) => '[' + body.split(/\s*,\s*/).join(', ') + ']')};
`;
writeFileSync(path.join(root, 'worker/lib/limits.js'), out);
console.log('wrote worker/lib/limits.js');
process.exit(0);
