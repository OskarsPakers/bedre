// Shared writer for worker/lib/limits.js (used by tools/gen-limits.mjs). LIMITS = { generated, runs, bands, maps: { <slug>: { runs, generated, modes, value, valueOther } } }.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { TRACE_STEP } from '../src/rules.js';
import { root } from './sim-lib.mjs';

export function writeLimits(limits) {
  const json = JSON.stringify(limits, null, 2).replace(/\[\s*([-\d.,\s]+?)\s*\]/g, (m, body) => '[' + body.split(/\s*,\s*/).join(', ') + ']');
  const out = `// GENERATED by tools/gen-limits.mjs -- do not edit by hand. Empirical maxima of autoplayer rounds PER MAP
// (greedy + cluster-greedy, with / without bots; the centre also covers all daily twists).
// worker/lib/validate.js applies SOFT x2 (suspect) and HARD x3 (reject) factors on top of these.
// maps.<slug>.modes.<mode>: gain[band]  max score gained per ${TRACE_STEP} s by start-radius band (bands = CFG.levels)   eaten10  max objects eaten per ${TRACE_STEP} s
//   cap  max final score   killMax  biggest single duel gain   value[kind] = [min, max] object value on that map (+30% for buildings)
export const LIMITS = ${json};
/** Limits of a map (unknown slug -> the centre). */
export const limitsFor = (map) => LIMITS.maps[map] || LIMITS.maps.centrs;
`;
  writeFileSync(path.join(root, 'worker/lib/limits.js'), out);
}
