// Tram physics + timetable + scoring. Pure (no DOM / THREE): the page drives it with a lever value, scripts drive it with autopilots.
//   s = arc length of the FIRST DOOR along the track (the stop marker is where this door should come to rest); the nose is NOSE m ahead of it.
// Outside world (set by the page / tests, all optional): run.env = { scan(sNose, maxD) -> { d, kind } | null  (nearest obstruction ahead on the track: another tram,
//   a person or vehicle on the rails), signals: [{ s, kind: 'road'|'block', aspect: 'g'|'y'|'r' }] sorted by s }.
import { SPEED, idealProfile } from './track.js';

export const TRAM = { nose: 3.78, length: 25.2, doors: [0, -5.04, -12.6, -17.64] };   // metres relative to the first door (forward positive)
export const PHYS = {
  vmax: SPEED.max, acc: 1.0, brake: 1.2, emergency: 2.5, drag: 0.03, tau: 0.28,    // m/s, m/s^2 (service brake 1.2, emergency 2.5), traction / brake response lag (s)
  rateUp: 1.5, rateDown: 2.2, rateBrake: 1.9,                                        // keyboard lever ramp speeds (per second)
  capacity: 110,                                                                      // passengers
};
/** door schedule of one stop: alighting person i steps out at alT(i), boarding person j starts walking at bT(j) and is aboard BWALK s later; everything in seconds after the doors are fully open */
export const BWALK = 1.7;
export function doorSchedule(alight, board) {
  const ia = Math.min(0.55, 3.6 / Math.max(1, alight)), ib = Math.min(0.85, 6 / Math.max(1, board));
  const tB = Math.max(1.0, 0.6 + Math.min(alight, 6) * ia * 0.7);
  const alT = (i) => 0.6 + i * ia, bT = (j) => tB + j * ib;
  const end = Math.max(alight ? alT(alight - 1) + 0.4 : 0, board ? bT(board - 1) + BWALK : 0);
  return { alT, bT, need: Math.max(3, Math.min(26, end + 0.8)) };
}
export const ZONE = { behind: -26, ahead: 10 };    // door-to-marker error window in which the doors may open: -26 m (short) .. +10 m (overshoot)
export const SCORE = { acc: 40, time: 30, smooth: 20, speed: 10 };
export const PEN = { redPass: 15, atp: 10, pedHit: 12 };   // points off the run total
export const PACE_REF = 0.955;                      // the reference ("good but human") driver that sets the timetable follows 95.5 % of the ideal speed profile
const mulberry = (a) => () => { a |= 0; a = (a + 0x6d2b79f5) | 0; let t = Math.imul(a ^ (a >>> 15), 1 | a); t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t; return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
const clamp = (v, a, b) => Math.min(b, Math.max(a, v));

/** how busy a stop is (waiting passengers ~ weight * 3): the central / interchange ones are the busiest */
const BUSY = { 'Centrāltirgus': 3.2, 'Autoosta': 2.6, 'Stacijas laukums': 3, 'Nacionālā opera': 2.4, '13. janvāra iela': 2.4, 'Grēcinieku iela': 2, 'Nacionālā bibliotēka': 2, 'Merķeļa iela': 1.8, 'Spīķeri': 1.8, 'Mežaparks / ZOO': 2.6, 'Bērnu pasaule': 1.8, 'Brīvības iela': 1.6, 'Dzirnavu iela': 1.5, 'Ezermalas iela': 1.4 };
export const busyOf = (name) => BUSY[name] ?? 1;

/**
 * The stops of a run (indices into track.stops) with the timetable. The timetable is generated by a REFERENCE RUN: the same physics (Run) driven by a good-but-human
 * autopilot (93 % of the ideal speed profile, comfortable braking, normal door cycles). due[i] = its arrival time, depart[i] = the moment its doors had closed
 * (+3 s: bell and a human's slack). A perfect driver is therefore slightly early at most stops; he waits for `depart` (early departure is not allowed) and arrives within a few seconds of `due`.
 */
export function makeRun(track, from, to, { seed = 7 } = {}) {
  const rng = mulberry(seed + from * 13);
  const stops = [];
  for (let i = from; i <= to; i++) {
    const st = track.stops[i], k = busyOf(st.name), last = i === to, first = i === from;
    const waiting = first ? 0 : Math.round((2 + rng() * 3) * k);
    stops.push({ idx: i, name: st.name, s: st.s, first, last, due: 0, depart: 0, leg: 0, dwell: 0, alight: last ? 99 : 0.18 + rng() * 0.3, board: last ? 0 : waiting, waitingAt: last ? 0 : waiting, busy: k });
  }
  const plan = { stops, from, to, ttDuration: 0, avgKmh: 0 };
  const ref = new Run(track, plan, { ref: true });
  const ctx = { pace: PACE_REF };
  let guard = 0; const traj = [];
  while (!ref.finished && guard++ < 400000) { if (guard % 30 === 1) traj.push(ref.s); const c = perfectDriver(ref, ctx); ref.setLever(c.lever, true); if (c.doors) ref.pressDoors(); if (c.bell) ref.ringBell(); ref.step(1 / 60); }
  stops.forEach((st, i) => {
    const r = ref.results.find((x) => x.idx === st.idx);
    st.due = r ? r.arrival : (i ? stops[i - 1].due + 60 : 0);
    st.depart = (ref.departures[st.idx] ?? st.due + 12) + 3.0;   // +1 s for the departure bell, +2 s slack of a human driver
    if (st.first) st.depart = 0;   // the run starts at the first movement
    st.dwell = st.last ? 0 : st.depart - st.due;
    st.leg = i ? st.due - stops[i - 1].depart : 0;
  });
  plan.traj = traj; plan.trajDt = 0.5;
  /** reference time at which the door passed s on its way to the stop after `from` (the leg's own samples only, so the standing at the stops does not blur it) */
  plan.refTimeAt = (s, sFrom) => { let lo = 0, hi = traj.length - 1; while (lo < hi) { const m = (lo + hi) >> 1; if (traj[m] < s) lo = m + 1; else hi = m; } let k = lo; if (sFrom !== undefined) { let a = 0, b = traj.length - 1; while (a < b) { const m = (a + b) >> 1; if (traj[m] <= sFrom + 0.5) a = m + 1; else b = m; } if (k < a) k = a; } const u = k > 0 && traj[k] > traj[k - 1] ? (s - traj[k - 1]) / (traj[k] - traj[k - 1]) : 1; return (k - 1 + clamp(u, 0, 1)) * 0.5; };   // door position of the reference run every 0.5 s: the other trams of the line follow it (a timetable-true lead / follower)
  const dist = stops[stops.length - 1].s - stops[0].s;
  plan.ttDuration = stops[stops.length - 1].due; plan.avgKmh = (3.6 * dist) / plan.ttDuration;
  return plan;
}

export function accuracyPoints(d) { const a = Math.abs(d); return a <= 0.5 ? [SCORE.acc, 'perfect'] : a <= 2 ? [32, 'good'] : a <= 5 ? [22, 'fair'] : a <= 10 ? [12, 'poor'] : [5, 'poor']; }
export function timePoints(e) { // e = arrival - due (s): + late, - early
  if (e > 8) return Math.max(0, SCORE.time - (e - 8) * 0.5);
  if (e < -8) return Math.max(0, SCORE.time - (-e - 8) * 0.75);
  return SCORE.time;
}
export const starsOf = (r) => (r >= 0.85 ? 3 : r >= 0.6 ? 2 : r >= 0.3 ? 1 : 0);

export class Run {
  constructor(track, plan, { startS, ref = false, env = null, pax } = {}) {
    this.track = track; this.plan = plan; this.stops = plan.stops; this.ref = ref; this.env = env || { scan: null, signals: [] };
    this.s = startS ?? plan.stops[0].s; this.v = 0; this.a = 0;
    this.lever = 0; this.leverTarget = 0; this.emergency = false;
    this.t = 0; this.time = 0;                      // time = run clock (starts at the first movement)
    this.started = false;
    this.next = 1;                                  // index into stops of the next stop to serve (0 = start stop, already "served")
    this.door = 0; this.doorState = 'closed';       // door: 0 closed .. 1 open; state closed|opening|open|closing
    this.doorWish = false;
    this.pax = pax ?? Math.round(10 + 8 * (plan.stops[0].busy || 1));
    this.dwell = null;                              // { stopIdx, t, need, alight, board, done, departAt }
    this.results = [];
    this.finished = false;
    this.events = [];
    this._leg = this._newLeg();
    this._lastA = 0; this._standT = 0; this._jerkF = 0;
    this.limit = track.limit(this.s);
    this.stats = { overspeedS: 0, curveOverS: 0, ebrakes: 0, maxV: 0, redPass: 0, atp: 0, pedHit: 0, bells: 0, heldS: 0, comfortSum: 0, comfortT: 0 };
    this.pendingOpen = false;
    this.awaitBell = true;                          // ready-to-depart flow: doors closed -> bell -> go
    this.bellT = -99; this._bellPush = 0;
    this.arrivals = {}; this.departures = {};       // by stop idx (reference run)
    this.excused = 0;                               // seconds of standing because of a red signal / a blocked line (do not count as lateness)
    this.comfort = 100; this.penalties = [];
    this.gap = Infinity; this.atpOn = false; this.nextSig = null; this.holdMsg = '';
    this.heldByEnv = false; this._sDep = this.s; this._envT = 0;
  }
  _newLeg() { return { jerkPen: 0, hardPen: 0, curvePen: 0, overInt: 0, overS: 0, emergencyUsed: false, maxJ: 0, hard: 0 }; }

  get stop() { return this.stops[this.next] || null; }
  get distToStop() { const st = this.stop; return st ? st.s - this.s : 0; }
  /** due time of the next stop minus the run clock (s); standing time at red / blocked line is excused */
  get dueIn() { const st = this.stop; return st ? st.due + this.excused - this.time : 0; }
  get doorsClosed() { return this.doorState === 'closed'; }
  get inZone() { const st = this.stop; if (!st) return false; const d = this.s - st.s; return d >= ZONE.behind && d <= ZONE.ahead; }
  get noseS() { return this.s + TRAM.nose; }
  get load() { return this.pax / PHYS.capacity; }
  /** seconds against the timetable (+ late, - early), excused time deducted: between stops the position is compared with the timetable's linear interpolation between the
   *  previous departure and the next arrival; standing at a stop it keeps the arrival error of that stop (the wait for the departure time is not "lateness") */
  get punctuality() {
    const st = this.stop, prev = this.stops[this.next - 1];
    if (!st || !this.started) return 0;
    if (this.pendingOpen || this.doorState !== 'closed' || (this.v < 0.3 && this.results.length && Math.abs(prev.s - this.s) < 12)) { const r = this.results[this.results.length - 1]; return r && !r.missed ? r.timeErr : 0; }
    const tr = this.plan.traj;
    if (tr && this.plan.refTimeAt) { const expect = this.plan.refTimeAt(this.s, prev.s) + (prev.first ? 0 : 3); return this.time - this.excused - expect; }
    const f = clamp((this.s - prev.s) / Math.max(1, st.s - prev.s), 0, 1), expect = prev.depart + f * Math.max(1, st.due - prev.depart);
    return this.time - this.excused - expect;
  }

  setLever(x, immediate = false) { this.leverTarget = clamp(x, -1, 1); if (immediate) this.lever = this.leverTarget; }
  pressDoors() { this.doorWish = true; }
  ringBell() { this.bellT = this.t; this.stats.bells++; this.awaitBell = false; this.events.push({ type: 'bell' }); }
  penalty(type, pts) { this.penalties.push({ type, pts, at: this.s }); this.comfort = Math.max(0, this.comfort - pts * 0.8); }

  step(dt) {
    if (this.finished) return;
    const P = PHYS, T = this.track;
    this.t += dt;
    // ---- lever (rate limited so a jab is still a smooth push) ---------------------------------------------------------------------------
    const tgt = this.emergency ? -1 : this.leverTarget;
    const rate = tgt > this.lever ? (this.lever < 0 ? P.rateBrake : P.rateUp) : (tgt >= 0 ? P.rateDown : P.rateBrake);
    this.lever += clamp(tgt - this.lever, -rate * dt, rate * dt);
    if (this.emergency) this.lever = -1;
    // ---- surroundings: obstruction ahead (ATP), next signal ----------------------------------------------------------------------------------
    const noseS = this.s + TRAM.nose, env = this.env;
    let ob = env.scan ? env.scan(noseS, 90) : null;
    this.gap = ob ? ob.d : Infinity; this.obKind = ob ? ob.kind : null;
    const safeV = Math.sqrt(2 * 1.5 * Math.max(0, this.gap - 4));
    const atp = this.gap < 90 && this.v > safeV * 0.97 && this.v > 0.3;
    if (atp && !this.atpOn && !this.ref) { this.events.push({ type: 'atp', kind: this.obKind }); if (this.obKind !== 'veh') { this.stats.atp++; this.penalty('atp', this.obKind === 'ped' ? Math.round(PEN.atp * 0.6) : PEN.atp); } }
    this.atpOn = atp;
    this.pedAhead = env.pedAhead ? env.pedAhead(this.stop ? this.distToStop + 25 : 1e9) : null;   // only a crossing BEFORE the next stop counts
    this.nextSig = null;
    const sg = env.signals;
    if (sg) for (let i = 0; i < sg.length; i++) if (sg[i].s > noseS - 0.2) { this.nextSig = sg[i]; break; }
    // signal passage: the nose crosses a signal showing red
    if (this._prevNose !== undefined && sg) for (const g of sg) if (g.s > this._prevNose && g.s <= noseS && g.aspect === 'r' && this.v > 0.4 && !this.ref) {
      this.stats.redPass++; this.penalty('redPass', PEN.redPass); this.events.push({ type: 'redpass', kind: g.kind });
    }
    this._prevNose = noseS;
    // ---- longitudinal dynamics ------------------------------------------------------------------------------------------------------------
    const doorsLocked = this.doorState !== 'closed' || this.pendingOpen;
    const bellLock = this.awaitBell && !this.ref;
    let cmd;
    if (this.emergency) cmd = -P.emergency;
    else if (doorsLocked) cmd = -P.brake;                       // traction interlock: doors open -> brakes held
    else if (atp) cmd = -Math.max(1.6, Math.min(P.emergency, this.v * this.v / (2 * Math.max(0.5, this.gap - 3))));
    else if (this.lever >= 0) {
      cmd = this.lever * P.acc * clamp((P.vmax - this.v) / 3, 0, 1);
      if (bellLock && this.lever > 0.05) { cmd = 0; this._bellPush += dt; if (this._bellPush > 1.4) this.ringBell(); }   // pushing power while waiting for the bell: it rings itself
    } else cmd = this.lever * P.brake;
    if (this.awaitBell && this.lever <= 0.05) this._bellPush = 0;
    const drag = P.drag + 0.0004 * this.v * this.v;
    let a = this.a + (cmd - this.a) * (1 - Math.exp(-dt / P.tau));
    let acc = a - (this.v > 0.02 ? drag : 0);
    let v = this.v + acc * dt;
    if (v <= 0 && acc <= 0) { v = 0; if (this.a < 0 && this.v > 0) this._stopJolt = -this.a; a = 0; acc = 0; }
    if (v > P.vmax) v = P.vmax;
    const prevV = this.v;
    this.v = v; this.a = a;
    const aEff = (v - prevV) / dt;
    this.s += (prevV + v) / 2 * dt;
    if (!this.started && (this.v > 0.05)) this.started = true;
    if (this.started) this.time += dt;
    // standing because the line is blocked or a signal is red: not the driver's fault
    this.heldByEnv = this.started && this.v < 0.4 && !doorsLocked && ((this.nextSig && this.nextSig.aspect === 'r' && this.nextSig.s - noseS < 40) || this.gap < 30);
    // delay caused by the surroundings (people at a crossing, a red / yellow signal, a tram ahead) is not the driver's lateness: the time lost against the limit is credited
    const envSlow = !doorsLocked && this.started && ((this.pedAhead && this.pedAhead.d < 170) || (this.nextSig && this.nextSig.aspect !== 'g' && this.nextSig.s - noseS < 160) || this.gap < 90);
    if (envSlow) this._envT = 18; else if (this._envT > 0) this._envT -= dt;   // the re-acceleration after the hindrance is part of it
    if (envSlow || this._envT > 0) {
      // the speed a free line would have allowed here: the limit, accelerating from where the tram last left a stop, braking for the next stop
      const sd = Math.max(0, this.s - this._sDep), stp = this.stop, toStop = stp ? Math.max(0, stp.s - this.s) : 1e9;
      const vfree = Math.min(this.limit * 0.97, Math.sqrt(2 * 0.9 * sd + 1), Math.sqrt(2 * 0.85 * toStop + 1));
      if (this.v < vfree * 0.88 && this.punctuality > -1.5) this.excused += 0.9 * dt * clamp(1 - this.v / Math.max(vfree, 1), 0, 1);   // credit only while the tram is really behind the timetable   
    }
    if (this.heldByEnv) this.stats.heldS += dt;
    if (this.v > this.stats.maxV) this.stats.maxV = this.v;
    // ---- comfort / speed accumulators (per leg); passengers standing in a full tram feel everything more ---------------------------------------------
    const L = this._leg, pax = this.pax > 0 ? 0.35 + 0.65 * Math.min(1, this.pax / 55) : 0.2;
    const jerk = (aEff - this._lastA) / dt; this._lastA = aEff;
    this._jerkF += (Math.abs(jerk) - this._jerkF) * Math.min(1, dt / 0.15);
    let cpen = 0;
    if (this.v > 0.5) {
      if (this._jerkF > 1.9) { const p = (this._jerkF - 1.9) * dt * 2.2 * pax; L.jerkPen += p; cpen += p; }
      if (-aEff > 1.55 && !this.emergency) { const p = (-aEff - 1.55) * dt * 6 * pax; L.hardPen += p; cpen += p; }
      L.maxJ = Math.max(L.maxJ, this._jerkF);
    }
    if (this.emergency && this.v > 0.5) { L.hardPen += dt * 7 * pax; cpen += dt * 7 * pax; L.emergencyUsed = true; }
    if (atp && this.v > 1) { L.hardPen += dt * 3 * pax; cpen += dt * 3 * pax; }
    this.limit = T.limit(this.s);
    const k = Math.abs(T.curvature(this.s)), aLat = this.v * this.v * k;
    this.latAccel = aLat;
    const ex = this.v - this.limit;
    this.overspeed = ex > 0.7;
    if (this.overspeed) { L.overInt += (ex - 0.7) * dt; L.overS += dt; this.stats.overspeedS += dt; cpen += Math.min(0.5, ex * 0.06) * dt * pax; }
    if (aLat > 1.45 && this.v > 3) { const p = (aLat - 1.45) * dt * 5 * pax; L.curvePen += p; cpen += p; this.stats.curveOverS += dt; this.curveOver = true; } else this.curveOver = false;
    // comfort meter: penalties pull it down (x7 so a rough stop shows), calm driving restores it slowly; late / early adds a small steady drag below
    this.comfort = clamp(this.comfort - cpen * 7 + (cpen < 1e-4 && this.v > 0.5 ? dt * 1.6 : 0), 0, 100);
    if (this.started) { this.stats.comfortSum += this.comfort * dt; this.stats.comfortT += dt; }
    // ---- doors / stops -------------------------------------------------------------------------------------------------------------------
    this._doors(dt);
    this._stopLogic(dt);
  }

  _doors(dt) {
    const standing = this.v < 0.03;
    if (this.doorState === 'closed') {
      if (this.pendingOpen && standing) {
        this._standT += dt;
        if (this.doorWish || this._standT > 0.8) { this.pendingOpen = false; this.doorState = 'opening'; this._standT = 0; this.events.push({ type: 'doorsOpening' }); }
      } else if (this.doorWish) this.events.push({ type: 'doorsDenied' });
    } else if (this.doorState === 'opening') {
      this.door = Math.min(1, this.door + dt / 1.1); if (this.door >= 1) { this.doorState = 'open'; if (this.dwell) this.dwell.t = 0; }
    } else if (this.doorState === 'open') {
      if (this.dwell) {
        this.dwell.t += dt;
        { const D = this.dwell, t = D.t; let a = 0, b = 0; while (a < D.alight && t >= D.sch.alT(a) + 0.3) a++; while (b < D.board && t >= D.sch.bT(b) + BWALK) b++;
          D.alN = a; D.boN = b; D.waitLeft = Math.max(0, (D.waitLeft0 ?? (D.waitLeft0 = D.waitLeft)) - b); if (!D.done) this.pax = D.pax0 - a + b; }
        if (!this.dwell.done && this.dwell.t >= this.dwell.need) { this.dwell.done = true; this.pax = this.dwell.paxAfter; this.events.push({ type: 'boarded', pax: this.pax }); }
        // doors close when boarding is over AND the scheduled departure time has come (no early departure); the button asks for it, it never skips the time
        const timeOk = this.ref || this.dwell.last || this.time >= this.dwell.departAt + this.excused - 1.1;
        this.dwell.waitDepart = this.dwell.done && !timeOk;
        if (this.dwell.done && timeOk && (this.doorWish || this.dwell.t >= this.dwell.need + 1.5 || this.dwell.last)) { this.doorState = 'closing'; this.events.push({ type: 'doorsClosing' }); }
      } else if (this.doorWish) this.doorState = 'closing';
    } else if (this.doorState === 'closing') {
      this.door = Math.max(0, this.door - dt / 1.1);
      if (this.door <= 0) {
        this.doorState = 'closed';
        if (this.dwell) this.departures[this.dwell.stopIdx] = this.time;
        this.dwell = null; this.events.push({ type: 'doorsClosed' });
        this.awaitBell = true; this._bellPush = 0; this._sDep = this.s;
        if (this.finishAfterDoors) { this.finished = true; this.events.push({ type: 'finished' }); }
      }
    }
    this.doorWish = false;
  }

  _stopLogic(dt) {
    const st = this.stop;
    if (!st) return;
    const d = this.s - st.s;
    if (this.v < 0.03 && d >= ZONE.behind && d <= ZONE.ahead && !this._arrived) { this._arrived = true; this._serve(st, d); }
    if (!this._arrived && d > ZONE.ahead) this._miss(st);
    if (this._arrived && this.v > 0.5) this._arrived = false;
  }

  _serve(st, d) {
    const L = this._leg;
    const [accP, accTxt] = accuracyPoints(d);
    const timeErr = this.time - (st.due + this.excused);
    this.arrivals[st.idx] = this.time;
    const timeP = st.first ? SCORE.time : timePoints(timeErr);
    const jolt = this._stopJolt || 0;
    const joltPen = this.pax > 0 ? clamp((jolt - 0.28) * 7, 0, 6) : 0;
    const smooth = clamp(SCORE.smooth - L.jerkPen - L.hardPen - L.curvePen - joltPen, 0, SCORE.smooth);
    const speedP = clamp(SCORE.speed - L.overInt * 1.4, 0, SCORE.speed);
    const total = Math.round(accP + timeP + smooth + speedP);
    const res = { idx: st.idx, name: st.name, missed: false, d, accP, accTxt, timeErr, timeP: Math.round(timeP), smooth: Math.round(smooth), speedP: Math.round(speedP), total, arrival: this.time, due: st.due, emergency: L.emergencyUsed, curveOverS: +this.stats.curveOverS.toFixed(1), jolt: +jolt.toFixed(2) };
    this.results.push(res);
    this.events.push({ type: 'served', res });
    this._leg = this._newLeg(); this._stopJolt = 0;
    const pax = this.pax;
    const alight = st.last ? pax : Math.min(pax, Math.round(pax * st.alight)), board = Math.min(st.board, PHYS.capacity - (pax - alight));
    // boarding takes longer the more people use the doors (a crowded door is slower); the last stop is always a plain alighting
    const sch = doorSchedule(alight, board), need = sch.need;
    this.dwell = { stopIdx: st.idx, t: 0, need, alight, board, done: false, paxAfter: pax - alight + board, pax0: pax, alN: 0, boN: 0, waitLeft: st.waitingAt, departAt: st.depart, last: st.last, sch };
    this.servedStop = st; this.pendingOpen = true; this._standT = 0;
    this.next++;
    if (this.next >= this.stops.length) this.finishAfterDoors = true;
  }

  _miss(st) {
    this.results.push({ idx: st.idx, name: st.name, missed: true, d: this.s - st.s, accP: 0, timeP: 0, smooth: 0, speedP: 0, total: 0, timeErr: this.time - st.due });
    this.events.push({ type: 'missed', name: st.name });
    this._leg = this._newLeg();
    this.next++;
    if (this.next >= this.stops.length) { this.finished = true; this.events.push({ type: 'finished' }); }
  }

  /** report card: points + stars per category + total + passenger satisfaction */
  summary() {
    const served = this.results.filter((r) => !r.missed), n = Math.max(1, this.stops.length - 1), missed = this.results.filter((r) => r.missed).length;
    const sum = (k) => this.results.reduce((a, r) => a + (r[k] || 0), 0);
    const stopPts = this.results.reduce((a, r) => a + r.total, 0), pen = this.penalties.reduce((a, p) => a + p.pts, 0);
    const points = Math.max(0, stopPts - pen), max = 100 * n;
    const comfAvg = this.stats.comfortT > 1 ? this.stats.comfortSum / this.stats.comfortT / 100 : 1;
    const cat = {
      precision: sum('accP') / (SCORE.acc * n),
      punctuality: sum('timeP') / (SCORE.time * n),
      comfort: 0.5 * (sum('smooth') / (SCORE.smooth * n)) + 0.5 * comfAvg,
      rules: clamp(1 - 0.34 * this.stats.redPass - 0.25 * this.stats.atp - 0.5 * Math.min(1, this.stats.overspeedS / 50) - 0.2 * this.stats.pedHit - 0.15 * missed, 0, 1),
    };
    const ratio = points / max;
    let stars = starsOf(ratio); if (stars < 1) stars = 1; if ((missed || this.stats.redPass) && stars > 2) stars = 2;
    const happy = Math.round(100 * clamp(0.35 * cat.comfort + 0.3 * cat.punctuality + 0.2 * cat.precision + 0.15 * cat.rules, 0, 1));
    return { points, max, stars, missed, ratio, time: this.time, stats: this.stats, penalties: this.penalties.slice(), cat, catStars: Object.fromEntries(Object.entries(cat).map(([k, v]) => [k, starsOf(v)])), happy, served: served.length, pax: this.pax };
  }
}

// ---- autopilots (test hooks; also what the reference run and the smoke test's "perfect" / "reckless" drivers use) -----------------------------
/** remaining ideal time from every sample of an idealProfile to its end (s) */
function withTail(p, ds) { const n = p.v.length, tail = new Float64Array(n); for (let k = n - 2; k >= 0; k--) tail[k] = tail[k + 1] + ds / Math.max(0.5, (p.v[k] + p.v[k + 1]) / 2); p.tail = tail; return p; }
/** Follows the limit profile, brakes comfortably onto the marker; obeys signals, brakes for obstructions, rings the bell (departure / crossings).
 *  ctx.pace scales the speed profile (the timetable's reference driver uses PACE_REF, the "perfect" test driver 1). Returns { lever, doors, bell }. */
export function perfectDriver(run, ctx = {}) {
  const T = run.track, st = run.stop, pace = ctx.pace ?? 1;
  if (!st) return { lever: 0, doors: false };
  if (run.doorState !== 'closed' || run.pendingOpen) return { lever: 0, doors: !!run.pendingOpen || !!(run.dwell && run.dwell.done), bell: false };
  if (run.awaitBell && !run.ref) return { lever: 0, doors: false, bell: true };
  const s0 = run.s, d = st.s - s0;
  const sPrev = run.stops[run.next - 1].s;
  const prof = ctx.prof && ctx.prof.stop === st ? ctx.prof : (ctx.prof = withTail({ stop: st, ...idealProfile(T, sPrev, st.s, 0.9, 0.85) }, T.ds));
  const i = Math.min(prof.v.length - 1, Math.max(0, Math.floor((s0 - prof.i0 * T.ds) / T.ds) + 4));
  let vt = prof.v[i] * (pace < 1 && d > 14 ? pace : 1);
  if (d < 14) { const a = 0.36 + 0.5 * clamp((d - 1) / 12, 0, 1); vt = Math.min(vt, Math.sqrt(2 * a * Math.max(0, d))); }
  // pacing: well ahead of the (excused) due time -> ease off a little (never more than 14 %), the rest of the leg is driven normally
  if (!run.ref && d > 90 && run.started && run.stop) { const k = Math.min(prof.tail.length - 1, Math.max(0, Math.floor((s0 - prof.i0 * T.ds) / T.ds))), early = (st.due + run.excused - run.time) - prof.tail[k] * 1.08 - 2; if (early > 0) vt *= 1 - 0.02 * Math.min(7, early); else if (early < -2) vt = Math.min(vt * (1 + 0.025 * Math.min(4, -early - 2)), run.limit * 1.035); }   // ... and a little faster when late
  if (d < 6 && d > 0.6) vt = Math.max(vt, Math.min(0.8, 0.25 + 0.1 * d));   // never stall short of the marker: creep in
  if (d < 0.2) vt = 0;
  // surroundings: red signal -> stop 3 m before it; anything on the track ahead -> keep a safe gap; a pedestrian ahead -> bell
  const nose = run.noseS, g = run.nextSig;
  if (g && g.aspect === 'r') { const dd = g.s - nose - 3; vt = Math.min(vt, Math.sqrt(2 * 0.8 * Math.max(0, dd))); }
  else if (g && g.aspect === 'y' && g.s - nose < 110) vt = Math.min(vt, 9);   // caution: the next block is occupied
  if (run.gap < 90) vt = Math.min(vt, Math.sqrt(2 * 0.75 * Math.max(0, run.gap - 9)));
  const pa = run.pedAhead;   // a person waits at the kerb / is crossing ahead: slow down early and ring the bell
  if (pa && pa.d < 170) { vt = Math.min(vt, 7 + Math.max(0, pa.d - 70) * 0.06); if (pa.d < 120 && run.t - run.bellT > 5) return { lever: 0, doors: false, bell: true }; }
  const dv = vt - run.v;
  let lever;
  if (dv > 0.1) lever = clamp(dv * 0.7, 0, 1);
  else if (dv < -0.1) lever = clamp(dv * 1.1, -1, 0);
  else lever = 0;
  if (d < 6 && run.v < 0.12 && d > 0.15 && run.gap > 20) lever = Math.max(lever, 0.12);
  if (d < 0.5 && d > -0.3) lever = run.v > 0.04 ? -0.5 : -1;
  if (d < -0.3) lever = -1;
  return { lever, doors: false, bell: false };
}
/** Full power, ignores the limits, signals and curves, brakes at the last moment with the emergency brake. */
export function recklessDriver(run) {
  const st = run.stop;
  if (!st) return { lever: 0, doors: false, emergency: false };
  if (run.doorState !== 'closed' || run.pendingOpen) return { lever: 0, doors: !!run.pendingOpen || !!(run.dwell && run.dwell.done), emergency: false };
  const d = st.s - run.s, brakeD = (run.v * run.v) / (2 * 2.5);
  if (d < brakeD && d > -6) return { lever: -1, doors: false, emergency: true };
  return { lever: 1, doors: false, emergency: false };
}
